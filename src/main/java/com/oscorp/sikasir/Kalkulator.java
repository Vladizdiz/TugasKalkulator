    private void BtnEqActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnEqActionPerformed
        // TODO add your handling code here:
        switch(pilih) {
            case 1:
                bilangan2 = Double.parseDouble(String.valueOf(TxtView.getText()));
                jumlah = bilangan1 + bilangan2;
                bilangan = Double.toString(jumlah);
                break;
            case 2:
                bilangan2 = Double.parseDouble(String.valueOf(TxtView.getText()));
                jumlah = bilangan1 - bilangan2;
                bilangan = Double.toString(jumlah);
                break;
            case 3:
                bilangan2 = Double.parseDouble(String.valueOf(TxtView.getText()));
                jumlah = bilangan1 * bilangan2;
                bilangan = Double.toString(jumlah);
                break;
            case 4:
                bilangan2 = Double.parseDouble(String.valueOf(TxtView.getText()));
                jumlah = bilangan1 / bilangan2;
                bilangan = Double.toString(jumlah);
                break;
        }
        if (jumlah % 1 == 0) {
            TxtView.setText(String.valueOf((int) jumlah));
        } else {
            TxtView.setText(String.valueOf(jumlah));
                    }
    }//GEN-LAST:event_BtnEqActionPerformed

